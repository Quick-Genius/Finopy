"""IaC execution wrapper — applies Terraform plans with safety guards."""

from __future__ import annotations

import tempfile
import os
import json
import structlog
from python_terraform import Terraform

logger = structlog.get_logger()


async def apply_terraform_plan(plan_content: str) -> dict:
    """Apply a Terraform plan in a sandboxed temporary directory.

    Args:
        plan_content: Terraform HCL configuration as a string.

    Returns:
        Execution result with stdout/stderr.

    Raises:
        RuntimeError: If terraform apply fails.
    """
    with tempfile.TemporaryDirectory(prefix="finops_tf_") as tmpdir:
        # Write the plan
        tf_file = os.path.join(tmpdir, "main.tf")
        with open(tf_file, "w") as f:
            f.write(plan_content)

        tf = Terraform(working_dir=tmpdir)

        # Init
        return_code, stdout, stderr = tf.init(capture_output=True)
        if return_code != 0:
            raise RuntimeError(f"Terraform init failed: {stderr}")

        # Plan first (dry-run)
        return_code, stdout, stderr = tf.plan(capture_output=True)
        if return_code != 0:
            raise RuntimeError(f"Terraform plan failed: {stderr}")

        logger.info("terraform_plan_output", output=stdout[:500])

        # Apply
        return_code, stdout, stderr = tf.apply(
            skip_plan=True,
            capture_output=True,
            auto_approve=True,
        )

        if return_code != 0:
            raise RuntimeError(f"Terraform apply failed: {stderr}")

        return {
            "status": "applied",
            "output": stdout[:1000],
            "working_dir": tmpdir,
        }


async def generate_rightsizing_tf(instance_id: str, new_type: str) -> str:
    """Generate Terraform config for EC2 instance rightsizing."""
    return f"""
# Auto-generated by FinOps Optimizer
# Action: Rightsize instance {instance_id} to {new_type}

resource "aws_instance" "rightsized" {{
  instance_type = "{new_type}"

  lifecycle {{
    prevent_destroy = true
  }}

  tags = {{
    ManagedBy    = "finops-optimizer"
    PreviousType = "auto-detected"
    Reason       = "rightsizing-recommendation"
  }}
}}
"""
